namespace bretts_services.Models.ViewModels;

/// <summary>
/// Identifies the direction used to sort a result set.
/// </summary>
public enum SortDirection
{
    /// <summary>
    /// Sorts values from lowest to highest.
    /// </summary>
    Ascending = 0,

    /// <summary>
    /// Sorts values from highest to lowest.
    /// </summary>
    Descending = 1,
}
